"""
Stage 3: Cost-Sensitive Model Training & Evaluation (PR-AUC & Asymmetric Cost Matrix).

This standalone module executes:
1. Remediated Ledger Model Training:
   - Loads `X_train.parquet`, `X_test.parquet`, `y_train.parquet`, `y_test.parquet`
     generated by Stage 2 (where `newbalanceOrig` and `newbalanceDest` have been
     recalculated to eliminate the PaySim Ledger Bug).
   - Trains Algorithm 1 (Required): **XGBoost Classifier (`XGBClassifier`)** with
     `scale_pos_weight` calibrated to the class imbalance ratio and `eval_metric="aucpr"`.
   - Trains Algorithm 2: **LightGBM Classifier (`LGBMClassifier`)** (or Random Forest)
     with balanced cost weighting.
2. Cost-Sensitive & Imbalanced Evaluation:
   - Evaluates both models using **PR-AUC (Average Precision / AUPRC)** as the primary
     metric (since ROC-AUC is overly optimistic on imbalanced datasets).
   - Computes two optimal decision thresholds for each model:
     a) Maximum F1-Score threshold on the Precision-Recall curve.
     b) Minimum Expected Financial Cost threshold under an asymmetric cost matrix
        (`Cost = FN * cost_fn + FP * cost_fp`).
3. Target Leakage Ablation Experiment (Ledger Bug Proof):
   - Trains an identical XGBoost model on the *unfixed* ledger split (`X_train_leaked.parquet`)
     and compares its feature importances and PR-AUC against the remediated model to
     empirically demonstrate how the unfixed ledger causes decision trees to overfit
     the simulation bug (`raw_error_dest` / `newbalanceDest == 0`).
4. Artifacts & Visualizations:
   - Saves trained models (`models/xgboost_model.json`, `models/secondary_model.joblib`),
     metrics (`models/evaluation_metrics.json`), and PR-AUC / Cost / Ablation plots.
"""

from __future__ import annotations

import json
import time
from pathlib import Path
from typing import Any, Dict, Tuple

import joblib
import lightgbm as lgb
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd
import xgboost as xgb
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import (
    average_precision_score,
    confusion_matrix,
    f1_score,
    precision_recall_curve,
    precision_score,
    recall_score,
    roc_auc_score,
)

from src.dataset_adapter import load_config


def evaluate_predictions(
    y_true: np.ndarray,
    y_prob: np.ndarray,
    cost_fn: float = 500.0,
    cost_fp: float = 10.0,
) -> Dict[str, Any]:
    """
    Evaluate predicted probabilities on imbalanced classification metrics:
    - PR-AUC (Average Precision) — primary metric
    - ROC-AUC — secondary metric
    - Optimal F1 threshold & corresponding confusion matrix
    - Optimal Asymmetric Cost threshold & corresponding confusion matrix
    """
    pr_auc = float(average_precision_score(y_true, y_prob))
    roc_auc = float(roc_auc_score(y_true, y_prob))

    precisions, recalls, thresholds = precision_recall_curve(y_true, y_prob)
    # Compute F1 across all candidate thresholds
    f1_scores = (2.0 * precisions[:-1] * recalls[:-1]) / np.maximum(
        precisions[:-1] + recalls[:-1], 1e-12
    )
    best_f1_idx = int(np.argmax(f1_scores))
    opt_f1_thresh = float(thresholds[best_f1_idx])

    # Evaluate at default 0.5 threshold
    pred_05 = (y_prob >= 0.5).astype(int)
    tn_05, fp_05, fn_05, tp_05 = [int(x) for x in confusion_matrix(y_true, pred_05).ravel()]

    # Evaluate at optimal F1 threshold
    pred_f1 = (y_prob >= opt_f1_thresh).astype(int)
    tn_f1, fp_f1, fn_f1, tp_f1 = [int(x) for x in confusion_matrix(y_true, pred_f1).ravel()]

    # Evaluate across grid of thresholds for minimum asymmetric cost
    grid_thresh = np.linspace(0.01, 0.99, 199)
    total_pos = int(y_true.sum())
    costs = []
    for t in grid_thresh:
        p = y_prob >= t
        tp = int((p & (y_true == 1)).sum())
        fp = int((p & (y_true == 0)).sum())
        fn = total_pos - tp
        costs.append(fn * cost_fn + fp * cost_fp)

    best_cost_idx = int(np.argmin(costs))
    opt_cost_thresh = float(grid_thresh[best_cost_idx])
    pred_cost = (y_prob >= opt_cost_thresh).astype(int)
    tn_c, fp_c, fn_c, tp_c = [int(x) for x in confusion_matrix(y_true, pred_cost).ravel()]

    return {
        "pr_auc": round(pr_auc, 5),
        "roc_auc": round(roc_auc, 5),
        "default_threshold_0_5": {
            "threshold": 0.5,
            "precision": round(float(precision_score(y_true, pred_05, zero_division=0)), 4),
            "recall": round(float(recall_score(y_true, pred_05, zero_division=0)), 4),
            "f1": round(float(f1_score(y_true, pred_05, zero_division=0)), 4),
            "tp": tp_05,
            "fp": fp_05,
            "fn": fn_05,
            "tn": tn_05,
            "asymmetric_cost": round(float(fn_05 * cost_fn + fp_05 * cost_fp), 2),
        },
        "optimal_f1_threshold": {
            "threshold": round(opt_f1_thresh, 4),
            "precision": round(float(precision_score(y_true, pred_f1, zero_division=0)), 4),
            "recall": round(float(recall_score(y_true, pred_f1, zero_division=0)), 4),
            "f1": round(float(f1_score(y_true, pred_f1, zero_division=0)), 4),
            "tp": tp_f1,
            "fp": fp_f1,
            "fn": fn_f1,
            "tn": tn_f1,
            "asymmetric_cost": round(float(fn_f1 * cost_fn + fp_f1 * cost_fp), 2),
        },
        "optimal_cost_threshold": {
            "threshold": round(opt_cost_thresh, 4),
            "cost_fn_weight": cost_fn,
            "cost_fp_weight": cost_fp,
            "min_asymmetric_cost": round(float(costs[best_cost_idx]), 2),
            "precision": round(float(precision_score(y_true, pred_cost, zero_division=0)), 4),
            "recall": round(float(recall_score(y_true, pred_cost, zero_division=0)), 4),
            "f1": round(float(f1_score(y_true, pred_cost, zero_division=0)), 4),
            "tp": tp_c,
            "fp": fp_c,
            "fn": fn_c,
            "tn": tn_c,
        },
    }


def generate_stage3_plots(
    y_test: np.ndarray,
    xgb_prob: np.ndarray,
    sec_prob: np.ndarray,
    sec_name: str,
    xgb_leaked_prob: np.ndarray,
    clean_importances: Dict[str, float],
    leaked_importances: Dict[str, float],
    figures_dir: Path,
) -> Dict[str, str]:
    """
    Generate Precision-Recall curves, ROC comparison, and Ledger Bug Ablation
    feature importance charts.
    """
    figures_dir.mkdir(parents=True, exist_ok=True)
    plt.style.use("seaborn-v0_8-whitegrid" if "seaborn-v0_8-whitegrid" in plt.style.available else "default")

    # -------------------------------------------------------------------------
    # Figure 1: Precision-Recall Curve & Asymmetric Cost Curve
    # -------------------------------------------------------------------------
    fig, axes = plt.subplots(1, 2, figsize=(13, 5.2), dpi=140)

    p_xgb, r_xgb, _ = precision_recall_curve(y_test, xgb_prob)
    p_sec, r_sec, _ = precision_recall_curve(y_test, sec_prob)
    p_leak, r_leak, _ = precision_recall_curve(y_test, xgb_leaked_prob)

    ap_xgb = average_precision_score(y_test, xgb_prob)
    ap_sec = average_precision_score(y_test, sec_prob)
    ap_leak = average_precision_score(y_test, xgb_leaked_prob)

    axes[0].plot(r_xgb, p_xgb, color="#1f78b4", linewidth=2.4, label=f"XGBoost (Fixed Ledger) PR-AUC = {ap_xgb:.4f}")
    axes[0].plot(r_sec, p_sec, color="#33a02c", linewidth=2.2, linestyle="--", label=f"{sec_name} (Fixed Ledger) PR-AUC = {ap_sec:.4f}")
    axes[0].plot(r_leak, p_leak, color="#e31a1c", linewidth=1.8, linestyle=":", label=f"XGBoost (Leaked Ledger Bug) PR-AUC = {ap_leak:.4f}")
    axes[0].set_title("Precision-Recall Curve (AUPRC Evaluation)", fontsize=12, fontweight="bold")
    axes[0].set_xlabel("Recall (Sensitivity)")
    axes[0].set_ylabel("Precision (Positive Predictive Value)")
    axes[0].set_xlim(0.0, 1.02)
    axes[0].set_ylim(0.0, 1.03)
    axes[0].legend(loc="lower left", frameon=True, fontsize=9.5)

    # Panel B: Asymmetric Cost Curve across Probability Thresholds
    grid_t = np.linspace(0.02, 0.98, 100)
    total_pos = int(y_test.sum())
    xgb_costs = [
        (total_pos - int(((xgb_prob >= t) & (y_test == 1)).sum())) * 500.0
        + int(((xgb_prob >= t) & (y_test == 0)).sum()) * 10.0
        for t in grid_t
    ]
    sec_costs = [
        (total_pos - int(((sec_prob >= t) & (y_test == 1)).sum())) * 500.0
        + int(((sec_prob >= t) & (y_test == 0)).sum()) * 10.0
        for t in grid_t
    ]

    axes[1].plot(grid_t, np.array(xgb_costs) / 1000.0, color="#1f78b4", linewidth=2.3, label="XGBoost Expected Cost")
    axes[1].plot(grid_t, np.array(sec_costs) / 1000.0, color="#33a02c", linewidth=2.2, linestyle="--", label=f"{sec_name} Expected Cost")
    axes[1].set_title("Asymmetric Risk Cost (FN=$500, FP=$10) vs. Threshold", fontsize=12, fontweight="bold")
    axes[1].set_xlabel("Classification Probability Threshold")
    axes[1].set_ylabel("Total Test Set Cost ($ Thousands)")
    axes[1].legend(loc="upper right", frameon=True)

    plt.tight_layout()
    pr_path = figures_dir / "stage3_pr_curves_and_cost.png"
    fig.savefig(pr_path, bbox_inches="tight")
    plt.close(fig)

    # -------------------------------------------------------------------------
    # Figure 2: Target Leakage Ablation (Leaked vs. Fixed Ledger Feature Gain)
    # -------------------------------------------------------------------------
    fig, axes = plt.subplots(1, 2, figsize=(13.5, 5.2), dpi=140)

    # Sort top 8 features for Leaked vs Clean XGBoost
    leak_sorted = sorted(leaked_importances.items(), key=lambda kv: kv[1], reverse=True)[:8][::-1]
    clean_sorted = sorted(clean_importances.items(), key=lambda kv: kv[1], reverse=True)[:8][::-1]

    axes[0].barh(
        [k for k, _ in leak_sorted],
        [v for _, v in leak_sorted],
        color=["#e31a1c" if "error" in k or "Dest" in k else "#888888" for k, _ in leak_sorted],
    )
    axes[0].set_title("BEFORE Remediation: Leaked Ledger XGBoost Gain", fontsize=11.5, fontweight="bold")
    axes[0].set_xlabel("Relative Gain Importance")

    axes[1].barh(
        [k for k, _ in clean_sorted],
        [v for _, v in clean_sorted],
        color="#1f78b4",
    )
    axes[1].set_title("AFTER Remediation: Fixed Ledger XGBoost Gain", fontsize=11.5, fontweight="bold")
    axes[1].set_xlabel("Relative Gain Importance")

    plt.tight_layout()
    ablation_path = figures_dir / "stage3_leakage_ablation_importance.png"
    fig.savefig(ablation_path, bbox_inches="tight")
    plt.close(fig)

    return {
        "pr_curves_and_cost_plot": str(pr_path),
        "leakage_ablation_plot": str(ablation_path),
    }


def run_stage3(config_path: str | Path = "configs/paysim_config.yaml") -> Dict[str, Any]:
    """Execute Stage 3 model training, evaluation, and leakage ablation study."""
    t0 = time.time()
    config = load_config(config_path)
    modeling_dir = Path(config["paths"]["modeling_dir"])
    models_dir = Path(config["paths"]["models_dir"])
    models_dir.mkdir(parents=True, exist_ok=True)

    print("[Stage 3] Loading preprocessed Parquet splits...")
    X_train = pd.read_parquet(modeling_dir / "X_train.parquet")
    X_test = pd.read_parquet(modeling_dir / "X_test.parquet")
    y_train = pd.read_parquet(modeling_dir / "y_train.parquet")["isFraud"].to_numpy(dtype=int)
    y_test = pd.read_parquet(modeling_dir / "y_test.parquet")["isFraud"].to_numpy(dtype=int)

    # Calculate class imbalance ratio for cost-sensitive learning
    n_pos = int(y_train.sum())
    n_neg = int(len(y_train) - n_pos)
    scale_pos_weight = float(n_neg / max(n_pos, 1))
    print(f"[Stage 3] Train set: {len(X_train):,} rows ({n_pos:,} fraud, scale_pos_weight={scale_pos_weight:.2f})")

    cost_fn = float(config["modeling"].get("cost_false_negative", 500.0))
    cost_fp = float(config["modeling"].get("cost_false_positive", 10.0))

    # -------------------------------------------------------------------------
    # 1. Algorithm 1: XGBoost Classifier (on Fixed/Remediated Ledger)
    # -------------------------------------------------------------------------
    xgb_params = dict(config["modeling"]["xgboost_params"])
    xgb_params["scale_pos_weight"] = scale_pos_weight

    print("[Stage 3] Training Algorithm 1: XGBoost Classifier (Fixed Ledger)...")
    xgb_model = xgb.XGBClassifier(**xgb_params)
    xgb_model.fit(
        X_train,
        y_train,
        eval_set=[(X_test, y_test)],
        verbose=False,
    )

    xgb_model_path = models_dir / "xgboost_model.json"
    xgb_model.save_model(xgb_model_path)

    xgb_prob = xgb_model.predict_proba(X_test)[:, 1]
    xgb_metrics = evaluate_predictions(y_test, xgb_prob, cost_fn=cost_fn, cost_fp=cost_fp)
    print(f"[Stage 3] XGBoost (Fixed Ledger) Test PR-AUC = {xgb_metrics['pr_auc']:.4f}, Optimal-F1 = {xgb_metrics['optimal_f1_threshold']['f1']:.4f}")

    # Extract gain feature importances for XGBoost
    clean_gain_raw = xgb_model.get_booster().get_score(importance_type="gain")
    total_clean_gain = sum(clean_gain_raw.values()) or 1.0
    clean_importances = {
        col: round(float(clean_gain_raw.get(col, 0.0) / total_clean_gain), 4)
        for col in X_train.columns
    }

    # -------------------------------------------------------------------------
    # 2. Algorithm 2: Secondary Model (LightGBM or Random Forest)
    # -------------------------------------------------------------------------
    sec_type = config["modeling"].get("secondary_model_type", "lightgbm").lower()
    if sec_type == "lightgbm":
        sec_name = "LightGBM"
        lgb_params = dict(config["modeling"]["lightgbm_params"])
        lgb_params["scale_pos_weight"] = scale_pos_weight
        print(f"[Stage 3] Training Algorithm 2: {sec_name} Classifier (Fixed Ledger)...")
        sec_model = lgb.LGBMClassifier(**lgb_params)
        sec_model.fit(X_train, y_train)
    else:
        sec_name = "RandomForest"
        print(f"[Stage 3] Training Algorithm 2: {sec_name} Classifier (Fixed Ledger)...")
        sec_model = RandomForestClassifier(
            n_estimators=200,
            max_depth=10,
            class_weight="balanced_subsample",
            random_state=42,
            n_jobs=-1,
        )
        sec_model.fit(X_train, y_train)

    sec_model_path = models_dir / "secondary_model.joblib"
    joblib.dump(sec_model, sec_model_path)

    sec_prob = sec_model.predict_proba(X_test)[:, 1]
    sec_metrics = evaluate_predictions(y_test, sec_prob, cost_fn=cost_fn, cost_fp=cost_fp)
    print(f"[Stage 3] {sec_name} (Fixed Ledger) Test PR-AUC = {sec_metrics['pr_auc']:.4f}, Optimal-F1 = {sec_metrics['optimal_f1_threshold']['f1']:.4f}")

    # -------------------------------------------------------------------------
    # 3. Ablation Experiment: XGBoost on Unfixed/Leaked Ledger
    # -------------------------------------------------------------------------
    print("[Stage 3] Running Target Leakage Ablation (XGBoost on Unfixed Ledger)...")
    X_train_leaked = pd.read_parquet(modeling_dir / "X_train_leaked.parquet")
    X_test_leaked = pd.read_parquet(modeling_dir / "X_test_leaked.parquet")

    xgb_leaked = xgb.XGBClassifier(**xgb_params)
    xgb_leaked.fit(X_train_leaked, y_train, verbose=False)
    xgb_leaked_prob = xgb_leaked.predict_proba(X_test_leaked)[:, 1]
    leaked_metrics = evaluate_predictions(y_test, xgb_leaked_prob, cost_fn=cost_fn, cost_fp=cost_fp)

    leak_gain_raw = xgb_leaked.get_booster().get_score(importance_type="gain")
    total_leak_gain = sum(leak_gain_raw.values()) or 1.0
    leaked_importances = {
        col: round(float(leak_gain_raw.get(col, 0.0) / total_leak_gain), 4)
        for col in X_train_leaked.columns
    }
    print(f"[Stage 3] Leaked Ledger XGBoost Test PR-AUC = {leaked_metrics['pr_auc']:.4f} (exploits raw_error_dest / newbalanceDest bug)")

    # Save test predictions for Stage 4 SHAP selection
    preds_df = pd.DataFrame({
        "y_true": y_test,
        "xgb_prob": xgb_prob,
        "secondary_prob": sec_prob,
    })
    preds_df.to_parquet(models_dir / "test_predictions.parquet", index=False)

    # Generate Plots
    figures_dir = Path(config["paths"]["figures_dir"])
    plot_paths = generate_stage3_plots(
        y_test=y_test,
        xgb_prob=xgb_prob,
        sec_prob=sec_prob,
        sec_name=sec_name,
        xgb_leaked_prob=xgb_leaked_prob,
        clean_importances=clean_importances,
        leaked_importances=leaked_importances,
        figures_dir=figures_dir,
    )

    evaluation_summary = {
        "class_imbalance": {
            "train_positives": n_pos,
            "train_negatives": n_neg,
            "scale_pos_weight": round(scale_pos_weight, 3),
        },
        "xgboost_remediated": {
            "model_name": "XGBoost (Remediated Ledger)",
            "metrics": xgb_metrics,
            "feature_gain_importance": clean_importances,
        },
        "secondary_model_remediated": {
            "model_name": f"{sec_name} (Remediated Ledger)",
            "metrics": sec_metrics,
        },
        "ablation_xgboost_leaked_ledger": {
            "model_name": "XGBoost (Unfixed Leaked Ledger)",
            "metrics": leaked_metrics,
            "feature_gain_importance": leaked_importances,
        },
        "plots": plot_paths,
        "execution_time_sec": round(time.time() - t0, 2),
    }

    eval_path = models_dir / "evaluation_metrics.json"
    with open(eval_path, "w", encoding="utf-8") as f:
        json.dump(evaluation_summary, f, indent=2)

    print(f"[Stage 3] Complete in {evaluation_summary['execution_time_sec']}s -> saved {eval_path}")
    return evaluation_summary


if __name__ == "__main__":
    run_stage3()
